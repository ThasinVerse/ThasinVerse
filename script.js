function getYTId(url) {
    if (!url) return null;
    var p = [/youtu\.be\/([^?&]+)/, /youtube\.com\/watch\?v=([^?&]+)/, /youtube\.com\/shorts\/([^?&]+)/, /youtube\.com\/embed\/([^?&]+)/];
    for (var i = 0; i < p.length; i++) {
        var m = url.match(p[i]);
        if (m) return m[1];
    }
    return null;
}

